export const QUAL_UR: Record<string, string> = {
  Middle: 'مڈل', Matric: 'میٹرک', Intermediate: 'انٹرمیڈیٹ', DAE: 'ڈپلومہ',
  Bachelor: 'بیچلر', Masters: 'ماسٹرز', MPhil: 'ایم فل', PhD: 'پی ایچ ڈی', Any: 'کوئی بھی',
};

export type Lang = 'en' | 'ur';
const dicts = { en, ur };

/** Translate outside React (background task, notifications). */
export function translate(lang: Lang, key: Key): string {
  return dicts[lang][key] ?? en[key];
}

export function useI18n() {
  const lang = useApp((s) => s.lang);
  const t = useCallback((key: Key) => dicts[lang][key] ?? en[key], [lang]);
  const isUr = lang === 'ur';
  return {
    t,
    lang,
    isUr,
    // Nastaliq needs extra line height; Poppins for English
    tf: (weight: 'regular' | 'bold' = 'regular') =>
      isUr
        ? { fontFamily: weight === 'bold' ? font.urduBold : font.urdu, lineHeight: undefined, writingDirection: 'rtl' as const }
        : { fontFamily: weight === 'bold' ? font.semi : font.regular },
    qual: (q: string | null) => (q ? (isUr ? QUAL_UR[q] ?? q : q) : isUr ? QUAL_UR.Any : 'Any'),
  };
}
