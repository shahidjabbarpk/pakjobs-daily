/* Config plugin: signs Android release builds (AAB/APK) with your upload key.
   Reads credentials/keystore.properties (never committed). If that file is
   missing, the build falls back to Expo's default (debug) signing.
   This keeps android/ fully generated by `npx expo prebuild`. */
const { withAppBuildGradle } = require('expo/config-plugins');

const LOADER = `
// --- release signing (added by plugins/withReleaseSigning.js) ---
def pjSigning = new Properties()
def pjSigningFile = rootProject.file('../credentials/keystore.properties')
if (pjSigningFile.exists()) { pjSigningFile.withInputStream { pjSigning.load(it) } }
`;

const RELEASE_CONFIG = `
        release {
            if (pjSigning['storeFile']) {
                storeFile rootProject.file('../credentials/' + pjSigning['storeFile'])
                storePassword pjSigning['storePassword']
                keyAlias pjSigning['keyAlias']
                keyPassword pjSigning['keyPassword']
            }
        }`;

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    let g = cfg.modResults.contents;
    if (g.includes('pjSigning')) return cfg;                 // already applied

    // 1) load the properties file before the android {} block
    g = g.replace(/\nandroid\s*\{/, `${LOADER}\nandroid {`);

    // 2) add a "release" entry next to the generated "debug" signing config
    g = g.replace(/signingConfigs\s*\{/, (m) => m + RELEASE_CONFIG);

    // 3) make the release build type use it (only when the key file exists)
    g = g.replace(/(buildTypes\s*\{[\s\S]*?release\s*\{[\s\S]*?)signingConfig\s+signingConfigs\.debug/,
      "$1signingConfig pjSigning['storeFile'] ? signingConfigs.release : signingConfigs.debug");

    if (!g.includes('signingConfigs.release')) throw new Error('withReleaseSigning: could not patch app/build.gradle');
    cfg.modResults.contents = g;
    return cfg;
  });
};
